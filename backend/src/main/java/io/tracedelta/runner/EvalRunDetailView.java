package io.tracedelta.runner;

import java.math.BigDecimal;
import java.time.LocalDateTime;

public record EvalRunDetailView(
        Long id,
        String name,
        String runType,
        String status,
        String statusReason,
        Long datasetId,
        Long datasetVersionId,
        String datasetNameSnapshot,
        Integer datasetVersionNo,
        String targetType,
        Long providerId,
        Long httpTargetId,
        String providerNameSnapshot,
        String modelSnapshot,
        String targetConfigSnapshotJson,
        Integer concurrency,
        Integer maxAttempts,
        Long requestTimeoutMs,
        Double rateLimitPerSec,
        Integer rateLimitBurst,
        BigDecimal maxCostUsd,
        Long maxTotalTokens,
        Long retryBaseDelayMs,
        Long retryMaxDelayMs,
        Integer totalCases,
        Integer completedCases,
        Integer succeededCases,
        Integer failedCases,
        Integer skippedCases,
        Long totalInputTokens,
        Long totalOutputTokens,
        BigDecimal totalCostUsd,
        Long avgLatencyMs,
        Long p95LatencyMs,
        Boolean budgetExceeded,
        String budgetExceededReason,
        Integer interruptedAttemptCount,
        Boolean rateLimitDegraded,
        Boolean cancelRequested,
        Boolean traceIncomplete,
        Integer traceDroppedCount,
        LocalDateTime createdAt,
        LocalDateTime startedAt,
        LocalDateTime finishedAt,
        LocalDateTime updatedAt) {

    public static EvalRunDetailView fromEntity(EvalRunEntity e) {
        return new EvalRunDetailView(
                e.getId(),
                e.getName(),
                e.getRunType(),
                e.getStatus(),
                e.getStatusReason(),
                e.getDatasetId(),
                e.getDatasetVersionId(),
                e.getDatasetNameSnapshot(),
                e.getDatasetVersionNo(),
                e.getTargetType(),
                e.getProviderId(),
                e.getHttpTargetId(),
                e.getProviderNameSnapshot(),
                e.getModelSnapshot(),
                e.getTargetConfigSnapshotJson(),
                e.getConcurrency(),
                e.getMaxAttempts(),
                e.getRequestTimeoutMs(),
                e.getRateLimitPerSec(),
                e.getRateLimitBurst(),
                e.getMaxCostUsd(),
                e.getMaxTotalTokens(),
                e.getRetryBaseDelayMs(),
                e.getRetryMaxDelayMs(),
                e.getTotalCases(),
                e.getCompletedCases(),
                e.getSucceededCases(),
                e.getFailedCases(),
                e.getSkippedCases(),
                e.getTotalInputTokens(),
                e.getTotalOutputTokens(),
                e.getTotalCostUsd(),
                e.getAvgLatencyMs(),
                e.getP95LatencyMs(),
                e.getBudgetExceeded(),
                e.getBudgetExceededReason(),
                e.getInterruptedAttemptCount(),
                e.getRateLimitDegraded(),
                e.getCancelRequested(),
                Boolean.TRUE.equals(e.getTraceIncomplete()),
                e.getTraceDroppedCount() == null ? 0 : e.getTraceDroppedCount(),
                e.getCreatedAt(),
                e.getStartedAt(),
                e.getFinishedAt(),
                e.getUpdatedAt());
    }
}
